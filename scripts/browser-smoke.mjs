const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import { createServer } from '../server.mjs';
const server = createServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => dialog.accept());
try {
  await page.goto(base);
  await page.waitForSelector('#metrics .metric');
  assert.equal(await page.locator('#metrics .metric').count(), 4);
  assert.match(await page.locator('#budget-preview').innerText(), /0,250/);
  assert.equal(await page.locator('#chart svg').count(), 1);
  await page.screenshot({ path: '/tmp/engenharia-desktop.png', fullPage: true });
  await page.locator('#scenario-kind').selectOption('study');
  await page.locator('[name="project"]').fill('Estudo de validação — Ribeirão');
  await page.locator('#demand').fill('0.5');
  assert.match(await page.locator('#result-state').innerText(), /não calculadas/);
  await page.getByRole('button', { name: 'Calcular estudo' }).click();
  assert.match(await page.locator('#metrics').innerText(), /Demanda acima/);
  assert.match(await page.locator('#scenario-state').innerText(), /Cenário em edição/);
  await page.locator('#bodEffluent').fill('2000');
  await page.getByRole('button', { name: 'Calcular estudo' }).click();
  assert.match(await page.locator('#warnings').innerText(), /OD negativo/);
  await page.locator('#velocity').fill('0');
  await page.getByRole('button', { name: 'Calcular estudo' }).click();
  assert.equal(await page.locator('#velocity').evaluate(el => el.validity.valid), false);
  await page.locator('#velocity').fill('0.25');
  await page.locator('#bodEffluent').fill('60');
  await page.locator('#demand').fill('0.1');
  await page.getByRole('button', { name: 'Calcular estudo' }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#export').click();
  const download = await downloadEvent;
  const exported = JSON.parse(await readFile(await download.path(), 'utf8'));
  assert.equal(exported.inputs.demand, 0.1);
  assert.equal(exported.illustrative, false);
  assert.equal(exported.metadata.project, 'Estudo de validação — Ribeirão');
  const imported = structuredClone(exported);
  imported.inputs.demand = 0.2;
  imported.metadata.project = '<img src=x onerror=alert(1)>';
  await page.locator('#file').setInputFiles({ name: 'estudo.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(imported)) });
  await page.waitForFunction(() => document.querySelector('#demand').value === '0.2');
  assert.equal(await page.locator('[name="project"]').inputValue(), imported.metadata.project);
  assert.equal(await page.locator('#report-metadata img').count(), 0);
  assert.match(await page.locator('#result-state').innerText(), /<img src=x/);
  await page.locator('#file').setInputFiles({ name: 'invalido.json', mimeType: 'application/json', buffer: Buffer.from('{"schemaVersion":99}') });
  await page.waitForSelector('#error:not([hidden])');
  assert.match(await page.locator('#error').innerText(), /incompatível/);
  assert.equal(await page.locator('#demand').inputValue(), '0.2');
  await page.locator('[name="project"]').fill('Estudo de validação');
  await page.getByRole('button', { name: 'Calcular estudo' }).click();
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('#report-inputs').isVisible(), true);
  assert.equal(await page.locator('form').isVisible(), false);
  await page.pdf({ path: '/tmp/engenharia-relatorio.pdf', format: 'A4', printBackground: true, preferCSSPageSize: true });
  await page.emulateMedia({ media: 'screen' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base);
  await page.waitForSelector('#chart svg');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: '/tmp/engenharia-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: interface desktop/mobile, cálculo, balanço excedido, esgotamento de OD, validação, exportação/importação JSON, conteúdo seguro, impressão/PDF, sem erros JS e sem rolagem horizontal mobile.');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
